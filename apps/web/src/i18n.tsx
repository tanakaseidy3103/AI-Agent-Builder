const DICTS: Record<Lang, Record<Key, string>> = { en, ja };

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("aab.lang");
    if (saved === "ja" || saved === "en") return saved;
  } catch {
    /* storage may be blocked */
  }
  return typeof navigator !== "undefined" && navigator.language?.startsWith("ja") ? "ja" : "en";
}

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "en", setLang: () => {} });

export function LangProvider({ children, lang: forced }: { children: ReactNode; lang?: Lang }) {
  const [lang, setLangState] = useState<Lang>(forced ?? initialLang);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("aab.lang", l);
    } catch {
      /* ignore */
    }
  };
  return <Ctx.Provider value={{ lang, setLang }}>{children}</Ctx.Provider>;
}

export function useLang() {
  return useContext(Ctx);
}

export function useT() {
  const { lang } = useContext(Ctx);
  return (key: Key, vars?: Record<string, string | number>) => {
    let s: string = DICTS[lang][key] ?? en[key];
    for (const [k, v] of Object.entries(vars ?? {})) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}
