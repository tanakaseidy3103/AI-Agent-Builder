"""Regression tests for the 2026-11-14 quality fixes (static checks never execute code; no Docker needed here):

- code.tests_inputs      tests that call run() with input breaking input_schema (RC-1a, audits/real-llm-recovery/03)
- code.tests             trivial assertions (constants only) and tests that never call run() do not count
- code.inputs_from_data  the entrypoint must read its input from `data`, not from the file system
- code.evals             an empty expectation ({} ) proves nothing and is rejected
- contains([] , x)       an empty expected list means "nothing found", no longer "anything"

The two real packages in tests/real_packages/ were generated by a local Ollama model before these fixes; each passed
static validation then and must fail it now, for the reason named.
"""
import json
from pathlib import Path

import pytest

from app.skills.jsonschema_lite import contains
from app.skills.reference import REFERENCE_DIR, load_reference
from app.skills.validation import validate_package

REAL = Path(__file__).parent / "real_packages"


def _real(name: str) -> dict[str, str]:
    return json.loads((REAL / f"{name}.json").read_text(encoding="utf-8"))["files"]


def _checks(files: dict[str, str]) -> dict[str, dict]:
    checks, _ = validate_package(files)
    return {c.id: {"status": c.status, "message": c.message} for c in checks}


def _with_tests(body: str) -> dict[str, str]:
    files = load_reference(REFERENCE_DIR / "python-code-analyzer")
    files["tests/test_main.py"] = "import unittest\nfrom main import run\n\n\nclass T(unittest.TestCase):\n" + body
    return files


# ---------- code.tests_inputs ----------

def test_list_input_for_an_object_schema_is_flagged():
    c = _checks(_with_tests(
        "    def test_a(self):\n        self.assertEqual(run([{'files': {}}])['count'], 0)\n"
        "    def test_b(self):\n        self.assertEqual(run({'files': {}})['count'], 0)\n"
        "    def test_c(self):\n        self.assertEqual(run({'files': {'a.py': ''}})['count'], 0)\n"))
    assert c["code.tests_inputs"]["status"] == "fail"
    assert "test_a (line 7): $: expected object, got list" in c["code.tests_inputs"]["message"]
    assert "test_b" not in c["code.tests_inputs"]["message"]


def test_name_bound_to_an_invalid_literal_and_missing_required_key_are_flagged():
    c = _checks(_with_tests(
        "    def test_a(self):\n        data = {'other': 1}\n        self.assertEqual(run(data)['count'], 0)\n"
        "    def test_b(self):\n        self.assertEqual(run({'files': {}})['count'], 0)\n"
        "    def test_c(self):\n        self.assertEqual(run({'files': {}})['count'], 0)\n"))
    assert c["code.tests_inputs"]["status"] == "fail"
    assert "missing required 'files'" in c["code.tests_inputs"]["message"]


def test_non_literal_inputs_are_not_guessed():
    c = _checks(_with_tests(
        "    def test_a(self):\n        src = 'x' * 3\n        self.assertEqual(run({'files': {'a.py': src}})['count'], 0)\n"
        "    def test_b(self):\n        self.assertEqual(run(make())['count'], 0)\n"
        "    def test_c(self):\n        self.assertEqual(run({'files': {}})['count'], 0)\n"))
    assert c["code.tests_inputs"]["status"] == "pass"


def test_real_find_todo_package_is_caught_by_the_input_check():
    c = _checks(_real("find-todo-and-fixme-comments-0.3.0"))
    assert c["code.tests_inputs"]["status"] == "fail"
    assert "expected object, got list" in c["code.tests_inputs"]["message"]


# ---------- code.tests: trivial assertions, tests that never run the Skill ----------

def test_constant_only_assertions_do_not_count():
    c = _checks(_with_tests(
        "    def test_a(self):\n        run({'files': {}})\n        self.assertTrue(True)\n"
        "    def test_b(self):\n        run({'files': {}})\n        self.assertEqual(1, 1)\n"
        "    def test_c(self):\n        self.assertEqual(run({'files': {}})['count'], 0)\n"))
    assert c["code.tests"]["status"] == "fail"
    assert "without assertions" in c["code.tests"]["message"] and "test_a" in c["code.tests"]["message"]
    assert "test_b" in c["code.tests"]["message"] and "test_c" not in c["code.tests"]["message"].split("never call")[0]


def test_a_test_that_never_calls_run_is_rejected_but_helpers_and_setup_count():
    idle = _checks(_with_tests(
        "    def test_a(self):\n        self.assertEqual(len('ab'), 2)\n"
        "    def test_b(self):\n        self.assertEqual(run({'files': {}})['count'], 0)\n"
        "    def test_c(self):\n        self.assertEqual(run({'files': {}})['count'], 0)\n"))
    assert idle["code.tests"]["status"] == "fail" and "never call run(): ['test_a']" in idle["code.tests"]["message"]
    files = load_reference(REFERENCE_DIR / "python-code-analyzer")
    files["tests/test_main.py"] = (
        "import unittest\nfrom main import run\n\n\ndef rules(src):\n    return run({'files': {'a.py': src}})['findings']\n\n\n"
        "class T(unittest.TestCase):\n    def setUp(self):\n        self.out = run({'files': {}})\n"
        "    def test_a(self):\n        self.assertEqual(self.out['count'], 0)\n"
        "    def test_b(self):\n        self.assertEqual(rules('x = 1'), [])\n"
        "    def test_c(self):\n        self.assertIn('findings', self.out)\n")
    assert _checks(files)["code.tests"]["status"] == "pass"


# ---------- code.inputs_from_data ----------

@pytest.mark.parametrize("snippet,flag", [
    ("    with open(data['path']) as f:\n        f.read()\n", "open()"),
    ("    import os\n    os.listdir('.')\n", "os.listdir()"),
    ("    import os\n    os.walk('.')\n", "os.walk()"),
    ("    import os\n    os.path.exists('x')\n", "path.exists()"),
    ("    import glob\n    glob.glob('*.py')\n", "glob.glob()"),
    ("    from pathlib import Path\n    Path('x').read_text()\n", "read_text()"),
])
def test_entrypoint_reading_the_file_system_is_flagged(snippet, flag):
    files = load_reference(REFERENCE_DIR / "python-code-analyzer")
    files["scripts/main.py"] += f"\n\ndef _helper(data):\n{snippet}"
    c = _checks(files)
    assert c["code.inputs_from_data"]["status"] == "fail" and flag in c["code.inputs_from_data"]["message"]


def test_ast_walk_and_dict_methods_are_not_file_access():
    files = load_reference(REFERENCE_DIR / "python-code-analyzer")  # uses ast.walk(tree)
    assert "ast.walk" in files["scripts/main.py"]
    assert _checks(files)["code.inputs_from_data"]["status"] == "pass"


def test_real_csv_package_that_opened_a_path_is_caught():
    """validate-csv-headers@0.1.0 took {"file_path": ...}: in the sandbox the file does not exist, the code reported every
    header as missing, and an eval case still passed. It must now fail statically, before any sandbox run."""
    c = _checks(_real("validate-csv-headers-0.1.0"))
    assert c["code.inputs_from_data"]["status"] == "fail"
    assert "open()" in c["code.inputs_from_data"]["message"] and "path.exists()" in c["code.inputs_from_data"]["message"]


# ---------- code.evals: empty expectations ----------

def _with_cases(cases: list) -> dict[str, str]:
    files = load_reference(REFERENCE_DIR / "python-code-analyzer")
    files["evals/cases.json"] = json.dumps(cases)
    return files


@pytest.mark.parametrize("expect", [{"contains": {}}, {"equals": {}}, {"contains": {"x": {}}}])
def test_empty_expectation_is_rejected(expect):
    cases = [{"name": "empty", "input": {"files": {}}, "expect": expect},
             {"name": "ok", "input": {"files": {}}, "expect": {"contains": {"count": 0}}}]
    c = _checks(_with_cases(cases))
    assert c["code.evals"]["status"] == "fail" and "empty: expectation is empty" in c["code.evals"]["message"]


def test_an_empty_list_is_a_real_expectation():
    cases = [{"name": "clean", "input": {"files": {}}, "expect": {"contains": {"findings": []}}},
             {"name": "ok", "input": {"files": {}}, "expect": {"contains": {"count": 0}}}]
    assert _checks(_with_cases(cases))["code.evals"]["status"] == "pass"


def test_real_packages_with_an_empty_expectation_are_caught():
    for name in ("find-todo-and-fixme-comments-0.3.0", "validate-csv-headers-0.1.0"):
        c = _checks(_real(name))
        assert c["code.evals"]["status"] == "fail" and "expectation is empty" in c["code.evals"]["message"], name


# ---------- contains semantics ----------

def test_empty_expected_list_means_nothing_found():
    assert contains({"findings": []}, {"findings": [], "count": 0})
    assert not contains({"findings": []}, {"findings": [{"line": 1}], "count": 1})  # was True before the fix
    assert not contains({"findings": []}, {"findings": None})
    # non-empty lists keep subset semantics
    assert contains({"findings": [{"line": 1}]}, {"findings": [{"line": 1, "file": "a"}, {"line": 2}]})


# ---------- every reference Skill still passes every static check ----------

@pytest.mark.parametrize("name", sorted(p.name for p in REFERENCE_DIR.iterdir() if p.is_dir()))
def test_reference_skills_pass_the_new_checks(name):
    c = _checks(load_reference(REFERENCE_DIR / name))
    for cid in ("code.tests", "code.tests_inputs", "code.inputs_from_data", "code.evals"):
        assert c[cid]["status"] == "pass", (cid, c[cid]["message"])
